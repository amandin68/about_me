/* Выбор языка до отрисовки страницы.

   Этот файл подключён в <head> без async и defer — то есть браузер выполнит
   его ДО того, как нарисует содержимое. Это важно: иначе посетитель, который
   выбрал английский, на долю секунды увидит русский текст, и страница
   мигнёт. Поэтому файл держим крошечным.

   Язык хранится в localStorage — это память самого браузера посетителя,
   она никуда не отправляется и нам недоступна.                            */

(function () {
  'use strict';

  var saved = null;

  // localStorage может быть недоступен: приватный режим, запрет на хранение
  // данных сайта. Тогда просто остаёмся на языке по умолчанию.
  try {
    saved = localStorage.getItem('lang');
  } catch (e) { /* молча игнорируем */ }

  // Выбора ещё не было — показываем русский. Он основной: так каждый
  // посетитель видит одно и то же, а язык меняется только осознанно,
  // кнопкой. Чтобы вместо этого угадывать язык по настройкам браузера,
  // замените строку ниже на:
  //   if (saved !== 'ru' && saved !== 'en') {
  //     saved = (navigator.language || '').toLowerCase().indexOf('ru') === 0 ? 'ru' : 'en';
  //   }
  if (saved !== 'ru' && saved !== 'en') saved = 'ru';

  document.documentElement.lang = saved;
}());
